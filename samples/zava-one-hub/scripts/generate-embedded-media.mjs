import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { EOL } from 'node:os';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const provenancePath = resolve(root, 'assets/media-provenance.json');
const outputPath = resolve(root, 'src/shared/media/embeddedMedia.ts');
const catalog = JSON.parse(readFileSync(provenancePath, 'utf8'));

const entries = catalog.assets.map((asset) => {
  const bytes = readFileSync(resolve(root, asset.path));
  return `  ${asset.key}: 'data:${asset.mimeType};base64,${bytes.toString('base64')}'`;
});

const generated = [
  '// AUTO-GENERATED by scripts/generate-embedded-media.mjs. Do not edit by hand.',
  '// Runtime media is embedded once for a deterministic, fully offline keynote demo.',
  '',
  'export const embeddedMedia: Readonly<Record<string, string>> = {',
  entries.join(`,${EOL}`),
  '};',
  ''
].join(EOL);

if (process.argv.includes('--check')) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== generated) {
    console.error('Embedded media is stale. Run npm run generate:media.');
    process.exit(1);
  }
  console.log(`Embedded media is current (${catalog.assets.length} assets).`);
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, generated, 'utf8');
  console.log(`Generated ${catalog.assets.length} embedded assets.`);
}