// Refreshes the snapshot of the Microsoft 365 & Power Platform community team shown on
// https://pnp.github.io/#team (data/team.json in github.com/pnp/pnp.github.io). The card bundles the
// names, so it asks no extra host on every card; only when the story is about one of these people
// does it load their portrait from pnp.github.io. Run: npm run update-pnp-team

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://raw.githubusercontent.com/pnp/pnp.github.io/main/data/team.json';
const OUT = fileURLToPath(new URL('../src/copilotComponents/CosmoPolite/lib/images/sources/pnpTeam.data.ts', import.meta.url));

const res = await fetch(SOURCE);
if (!res.ok) {
  throw new Error(`${SOURCE} answered ${res.status}`);
}
const team = await res.json();
const rows = team
  .filter((p) => typeof p.name === 'string' && /^images\/team\/[a-z0-9-]+\.(webp|jpe?g|png)$/i.test(p.img || ''))
  .map((p) => [p.name.trim(), p.img.replace(/^images\/team\//, '')])
  .sort((a, b) => a[0].localeCompare(b[0], 'en'));

const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  OUT,
  `// Generated by scripts/update-pnp-team.mjs on ${today} from ${SOURCE}. Do not edit by hand.\n` +
    `// [name, portrait file under https://pnp.github.io/images/team/]\n\n` +
    `export const PNP_TEAM: ReadonlyArray<readonly [string, string]> = [\n` +
    rows.map(([name, file]) => `  [${JSON.stringify(name)}, ${JSON.stringify(file)}]`).join(',\n') +
    `\n];\n`
);
console.log(`${rows.length} team members → ${OUT}`);
